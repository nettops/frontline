/**
 * The rack, copied row for row out of `prototypes/pixel-arms.html`.
 *
 * Generated. Every sprite is 48 x 16, muzzle left, and the class is legible
 * from how much of the cell the thing fills — which is the whole point of a
 * fixed cell and the reason there is no size column anywhere in the design.
 *
 * The finishes are the sheet's recolouring trick pointed at provenance rather
 * than rarity: one shape, three palettes. `config/pieces.ts` decides which
 * finish a piece wears, and two provenances share `blued` because a serial is
 * a serial — what separates them is whose paper trail it is.
 *
 * Edit the prototype and re-run the generator, not this file.
 */

/** '0' outline · '1'-'4' metal, dark to bright · '5'-'7' walnut · '8''9' brass. */
export const FINISHES: Record<'blued' | 'blacked' | 'nickel', [string, string, string, string]> = {
  'blued': ['#171a1e', '#2b333a', '#3d5464', '#6b7f8c'],
  'blacked': ['#101012', '#1c1c1f', '#2a2a2e', '#3d3d42'],
  'nickel': ['#4a4a4e', '#7d7d82', '#b0b0b4', '#ded3bc'],
};

const FIXED: Record<string, string> = {
  '0':'#0c0a09',
  '5':'#3b2519',
  '6':'#5f3d27',
  '7':'#855838',
  '8':'#7d6720',
  '9':'#c9a227',
  'q':'#6d1b16',
  'r':'#c2352b',
  'R':'#dd5347',
  'o':'#4f6337',
  'p':'#85a45c',
  'g':'#15110e',
  'w':'#ded3bc',
};

/** The palette a finish paints with. */
export function armsPalette(finish: 'blued' | 'blacked' | 'nickel'): Record<string, string> {
  const m = FINISHES[finish];
  return { ...FIXED, '1': m[0], '2': m[1], '3': m[2], '4': m[3] };
}

