/**
 * City conditions: the world having a bad month independently of you.
 *
 * These are not events with buttons. A condition is a state the whole city is
 * in for a few weeks, it changes the numbers every other system already reads,
 * and it arrives because of something true about the board — a case going to
 * trial, a family bleeding out, too much money moving through fronts.
 *
 * Effects are plain multipliers so a condition never needs a special case in
 * the simulation. A key absent from `effects` is 1.
 */

export type WorldEffectKey =
  /** Operation payouts. */
  | 'payout'
  /** Added to operation success chance, as a fraction. Not a multiplier. */
  | 'successDelta'
  /** Heat generated by everything. */
  | 'heatGain'
  /** Front revenue. */
  | 'businessRevenue'
  /** Laundering capacity. */
  | 'launderCapacity'
  /** How readily the other families act. */
  | 'rivalAggression'
  /** How fast agencies build a case. */
  | 'agencyWork';

export interface WorldConditionDef {
  id: string;
  name: string;
  /** One line for the status strip. */
  summary: string;
  /** The memo body when it arrives. */
  body: string;
  tone: 'good' | 'bad' | 'mixed';
  weight: number;
  durationDays: [min: number, max: number];
  /** Days before this one can come round again. */
  cooldownDays: number;
  effects: Partial<Record<WorldEffectKey, number>>;
  /**
   * What has to be true for this to be possible. Read from a small summary of
   * the board rather than GameState, so this file stays free of simulation
   * imports and stays a config file.
   */
  requires?: (board: WorldBoard) => boolean;
}

/** The handful of facts a condition is allowed to care about. */
export interface WorldBoard {
  day: number;
  heat: number;
  openCases: number;
  /** Highest stage index reached by any open case, 0..8. */
  worstCaseStage: number;
  crewSize: number;
  districtsHeld: number;
  businesses: number;
  /** Any two families currently fighting. */
  warInCity: boolean;
  /** A rival below a third of their starting muscle. */
  bleedingRival: boolean;
  weeklyLaundered: number;
}

